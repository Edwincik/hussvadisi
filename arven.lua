    local function shouldDash(position, threats, goalDistance)
        if not SETTINGS.autoDash or not isRunnerActive() then return false end
        local now = os.clock(); if now - runtime.dashAt < 0.28 then return false end
        if #threats == 0 then return false end
        local nearestDistance = math.huge; local nearestThreat = nil
        local immediateDanger = false; local hardBlock = false
        local imminentTime = math.huge
        for _, threat in ipairs(threats) do
            if threat.distance < nearestDistance then nearestDistance = threat.distance; nearestThreat = threat end
            local gap = tonumber(threat.interceptGap) or math.huge
            local danger = math.max(tonumber(threat.danger) or 4, 4)
            imminentTime = math.min(imminentTime, tonumber(threat.timeToDanger) or math.huge)
            if threat.tackle and (gap <= danger * 1.12 or (threat.timeToDanger or math.huge) <= 0.38 or threat.distance <= 10) then
                immediateDanger = true
            elseif threat.preTackle and (gap <= danger * 1.05 and (threat.timeToDanger or math.huge) <= 0.48) then
                immediateDanger = true
            elseif threat.collisionRisk and (gap <= danger * 1.02 and (threat.timeToDanger or math.huge) <= 0.42) then
                immediateDanger = true
            end
        end
        local currentPath = runtime.path
        if currentPath.Magnitude > 0.05 then
            local pathClearance = routeClear(position, currentPath, threats)
            if pathClearance < -2.0 and nearestDistance <= 18 then hardBlock = true end
        end
        if runtime.sideGapDirection.Magnitude > 0.05 and os.clock() < runtime.sideGapUntil and nearestDistance <= 14 then
            local sideClearance = routeClear(position, runtime.sideGapDirection, threats)
            if sideClearance >= SETTINGS.sideGapMinClearance and imminentTime <= 0.55 then return true end
        end
        if immediateDanger then return true end
        if hardBlock and nearestDistance <= 15 and imminentTime <= 0.55 then return true end
        if nearestThreat and nearestDistance <= 9 and imminentTime <= 0.45 then return true end
        return false
    end
    local function runnerGoal(position, now)
        runtime.goalMode = _OO1l1ll(511)
        local goal = select(1, chooseSafeGoal(position))
        if not goal and SETTINGS.emergencySafeZone then goal = getSafeFallback(position) end
        runtime.goal = goal; return goal
    end
    local function routeDistance(position, goal, target)
        local a = flat(position); local b = flat(goal); local p = flat(target)
        local line = b - a; local lengthSquared = line:Dot(line)
        if lengthSquared < 0.01 then return (p - a).Magnitude, 0 end
        local t0 = math.clamp((p - a):Dot(line) / lengthSquared, 0, 1)
        local closest = a + line * t0
        return (p - closest).Magnitude, t0
    end
    local function validReviveTarget(target)
        if not target or not target.Parent then return false end
        if runtime.justGotUp and os.clock() - runtime.justGotUpAt < 6 then return false end
        local character = target.Character
        local root = character and character:FindFirstChild(_OO1l1ll(519))
        if not root then return false end
        if character:GetAttribute(_OO1l1ll(549)) ~= true or character:GetAttribute(_OO1l1ll(528)) ~= true then return false end
        local helper = character:GetAttribute(_OO1l1ll(550))
        return helper == nil or helper == LocalPlayer.UserId
    end
    local function chooseAssistTarget(position, safeGoal, now)
        if not safeGoal then runtime.assistMode = nil; runtime.assistTarget = nil; return nil, nil end
        if runtime.justGotUp and now - runtime.justGotUpAt < 6 then
            runtime.reviveTarget = nil; runtime.reviveStarted = false
            runtime.assistMode = nil; runtime.assistTarget = nil
            return nil, nil
        end
        local currentAssist = runtime.assistTarget
        if runtime.assistMode == _OO1l1ll(552) then
            if validReviveTarget(currentAssist) then
                local targetRoot = getRoot(currentAssist)
                if targetRoot then
                    local distance = flat(targetRoot.Position - position).Magnitude
                    local lateral = routeDistance(position, safeGoal, targetRoot.Position)
                    if runtime.reviveStarted or (distance <= SETTINGS.reviveMaxDistance and (lateral <= 24 or distance <= RESCUE_RANGE + 5)) then
                        return currentAssist, _OO1l1ll(552)
                    end
                end
            end
            if runtime.reviveStarted then return currentAssist, _OO1l1ll(552) end
            runtime.assistMode = nil; runtime.assistTarget = nil
        elseif runtime.assistMode == _OO1l1ll(548) then
            if currentAssist and currentAssist.Parent then
                local distance = flat(currentAssist.Position - position).Magnitude
                local lateral = routeDistance(position, safeGoal, currentAssist.Position)
                if distance <= SETTINGS.gemMaxDistance and lateral <= 18 then return currentAssist, _OO1l1ll(548) end
            end
            runtime.assistMode = nil; runtime.assistTarget = nil
        end
        local reviveCandidate
        if SETTINGS.autoRevive then
            local target = findDownedPlayer(position)
            if target then
                local targetRoot = getRoot(target)
                if targetRoot then
                    local distance = flat(targetRoot.Position - position).Magnitude
                    local lateral, t0 = routeDistance(position, safeGoal, targetRoot.Position)
                    if distance <= SETTINGS.reviveMaxDistance and t0 <= 1.05 and (lateral <= 24 or distance <= RESCUE_RANGE + 5) then
                        reviveCandidate = target
                    end
                end
            end
        end
        local gemCandidate
        if SETTINGS.autoGems then
            refreshGems(now, position)
            local gem = runtime.gemTarget
            if gem and gem.Parent then
                local distance = flat(gem.Position - position).Magnitude
                local lateral, t0 = routeDistance(position, safeGoal, gem.Position)
                if distance <= SETTINGS.gemMaxDistance and t0 <= 1.05 and lateral <= 18 then gemCandidate = gem end
            end
        end
        if SETTINGS.reviveBeforeGems and reviveCandidate then
            runtime.assistMode = _OO1l1ll(552); runtime.assistTarget = reviveCandidate; runtime.assistSince = now
            return reviveCandidate, _OO1l1ll(552)
        end
        if gemCandidate then
            runtime.assistMode = _OO1l1ll(548); runtime.assistTarget = gemCandidate; runtime.assistSince = now
            return gemCandidate, _OO1l1ll(548)
        end
        if reviveCandidate then
            runtime.assistMode = _OO1l1ll(552); runtime.assistTarget = reviveCandidate; runtime.assistSince = now
            return reviveCandidate, _OO1l1ll(552)
        end
        return nil, nil
    end
    local function handleGemArrival(position, now)
        local gem = runtime.gemTarget; if not gem or not gem.Parent then return end
        if flat(gem.Position - position).Magnitude <= SETTINGS.gemCollectDistance then
            runtime.gemIgnored[gem] = now + 0.7; runtime.gemTarget = nil
