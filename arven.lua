    end
    local function movementStuck(now, position)
        local previous = runtime.lastMovePosition
        if not previous then runtime.lastMovePosition = position; runtime.lastMove = now; runtime.stuck = false; return end
        if flat(position - previous).Magnitude >= 0.5 then
            runtime.lastMovePosition = position; runtime.lastMove = now; runtime.stuck = false
        elseif now - runtime.lastMove > 0.55 then
            runtime.stuck = true; runtime.lastMove = now; runtime.lastMovePosition = position
        end
    end

