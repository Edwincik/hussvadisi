    local function corridorAxes(position, goal)
        refreshSafezones()
        local a, b = safezone.a, safezone.b
        if not a or not b then return nil, nil, nil end
        local axis = flat(b.center - a.center)
        if axis.Magnitude < 0.05 then return nil, nil, nil end
        if math.abs(axis.X) >= math.abs(axis.Z) then axis = Vector3.new(axis.X >= 0 and 1 or -1, 0, 0)
        else axis = Vector3.new(0, 0, axis.Z >= 0 and 1 or -1) end
        local toGoal = flat(goal - position)
        if toGoal.Magnitude > 0.05 and axis:Dot(toGoal) < 0 then axis = -axis end
        local lateral = Vector3.new(-axis.Z, 0, axis.X)
        local center = (a.center + b.center) * 0.5
        return axis, lateral, center
    end
    local function clearCorridorLock()
        runtime.corridorActive = false
        runtime.corridorGoal = Vector3.zero; runtime.corridorCenter = Vector3.zero
        runtime.corridorAxis = Vector3.zero; runtime.corridorGapWidth = 0
        runtime.corridorStartedAt = -math.huge
    end
    local function findCorridorGoal(position, goal, threats, now)
        if not SETTINGS.corridorEnabled or #threats < 2 then clearCorridorLock() return nil end
        local axis, lateral, center = corridorAxes(position, goal)
        if not axis then clearCorridorLock() return nil end
        local forwardDistance = (center - position):Dot(axis)
        if forwardDistance < -12 or forwardDistance > SETTINGS.corridorApproachDistance then clearCorridorLock() return nil end
        local lineLat = center:Dot(lateral)
        local blockers = {}
        for _, threat in ipairs(threats) do
            local longitudinal = math.abs((threat.position - center):Dot(axis))
            local lateralPos = (threat.position - center):Dot(lateral)
            if longitudinal <= SETTINGS.corridorCenterRange and threat.distance <= 100 then
                blockers[#blockers + 1] = { threat=threat, lateral=lateralPos,
                    buffer=math.clamp(threat.danger * 0.38, 2.25, 5.25) }
            end
        end
        if #blockers < 2 then
            if runtime.corridorActive and now - runtime.corridorStartedAt <= SETTINGS.corridorLockTime then return runtime.corridorGoal end
            clearCorridorLock() return nil
        end
        table.sort(blockers, function(x, y) return x.lateral < y.lateral end)
        local bestCenter, bestWidth, bestScore = nil, -math.huge, -math.huge
        local low, high = math.huge, -math.huge
        for _, item in ipairs(blockers) do
            low = math.min(low, item.lateral - item.buffer)
            high = math.max(high, item.lateral + item.buffer)
        end
        local gaps = {}
        for i = 1, #blockers - 1 do
            local left = blockers[i].lateral + blockers[i].buffer
            local right = blockers[i + 1].lateral - blockers[i + 1].buffer
            if right > left then gaps[#gaps + 1] = {left=left, right=right, center=(left + right) * 0.5} end
        end
        local lateralMin = math.min(low - 9, lineLat - 28)
        local lateralMax = math.max(high + 9, lineLat + 28)
        if blockers[1].lateral - blockers[1].buffer > lateralMin then
            gaps[#gaps + 1] = {left=lateralMin, right=blockers[1].lateral - blockers[1].buffer,
                center=(lateralMin + blockers[1].lateral - blockers[1].buffer) * 0.5}
        end
        if blockers[#blockers].lateral + blockers[#blockers].buffer < lateralMax then
            gaps[#gaps + 1] = {left=blockers[#blockers].lateral + blockers[#blockers].buffer, right=lateralMax,
                center=(blockers[#blockers].lateral + blockers[#blockers].buffer + lateralMax) * 0.5}
        end
        for _, gap in ipairs(gaps) do
            local width = gap.right - gap.left
            if width >= SETTINGS.corridorMinWidth then
                local lateralOffset = gap.center - lineLat
                local linePoint = center + lateral * lateralOffset
                local aheadPoint = linePoint + axis * SETTINGS.corridorPassDistance
                local entryPoint = linePoint - axis * math.min(12, math.max(6, forwardDistance * 0.15))
                local entryClear = routeClear(position, flat(entryPoint - position), threats)
                local passClear = routeClear(position, flat(aheadPoint - position), threats)
                local edgeSafe = edgeDirectionClear(linePoint - axis * 4, axis, position.Y, 8)
                local centrality = 1 - math.min(math.abs(lateralOffset) / 28, 1)
                local score = width * 2.8 + centrality * 6 + math.min(passClear, 15) * 1.4 + math.min(entryClear, 10)
                if edgeSafe then score = score + 4 else score = score - 6 end
                if passClear < -1.5 or entryClear < -1.5 then score = score - 20 end
                if score > bestScore then bestScore = score; bestCenter = gap.center; bestWidth = width end
            end
        end
        if not bestCenter then
            if runtime.corridorActive and now - runtime.corridorStartedAt <= SETTINGS.corridorLockTime then
                local lockedProgress = (position - runtime.corridorCenter):Dot(runtime.corridorAxis)
                if lockedProgress > -8 and lockedProgress < SETTINGS.corridorPassDistance + 10 then return runtime.corridorGoal end
            end
            clearCorridorLock() return nil
        end
        if runtime.corridorActive then
            local sameAxis = runtime.corridorAxis:Dot(axis) > 0.98
            local sameCenter = math.abs((runtime.corridorCenter - center):Dot(lateral) - (bestCenter - lineLat)) <= 5
            local progress = (position - runtime.corridorCenter):Dot(runtime.corridorAxis)
            if sameAxis and sameCenter and progress > -10 and progress < SETTINGS.corridorPassDistance + 12 then return runtime.corridorGoal end
        end
        local gapOffset = bestCenter - lineLat
        local linePoint = center + lateral * gapOffset
        local passPoint = linePoint + axis * SETTINGS.corridorPassDistance
        runtime.corridorActive = true
        runtime.corridorGoal = Vector3.new(passPoint.X, position.Y, passPoint.Z)
        runtime.corridorCenter = linePoint
        runtime.corridorAxis = axis
        runtime.corridorGapWidth = bestWidth
        runtime.corridorStartedAt = now
        return runtime.corridorGoal
    end
    local function corridorDirection(position, goal, threats)
        local desired = flat(goal - position); if desired.Magnitude < 0.05 then return Vector3.zero end
        desired = desired.Unit
        local candidates = {}
        if runtime.sideGapDirection.Magnitude > 0.05 and os.clock() < runtime.sideGapUntil then addDirection(candidates, runtime.sideGapDirection) end
        addDirection(candidates, desired)
        for _, angle in ipairs({12, -12, 24, -24, 38, -38, 52, -52, 70, -70, 90, -90}) do addDirection(candidates, rotate(desired, angle)) end
        local best = desired; local bestScore = -math.huge
        for _, candidate in ipairs(candidates) do
            local progress = candidate:Dot(desired)
            if progress >= -0.05 then
                local clearance = routeClear(position, candidate, threats)
                local score = progress * 8 + math.min(clearance, 16) * 2.2
                if clearance < 0 then score = score - math.abs(clearance) * 16
                elseif clearance < 4 then score = score - (4 - clearance) * 7 end
                if score > bestScore then bestScore = score; best = candidate end
            end
        end
        return best.Unit
    end
    local function chooseSideGapDirection(position, desired, threats)
        if not SETTINGS.sideGapEnabled or #threats == 0 then return nil, nil, -math.huge end
        local front = flat(desired); if front.Magnitude < 0.05 then return nil, nil, -math.huge end
        front = front.Unit
        local lateral = Vector3.new(-front.Z, 0, front.X)
        local nearest, nearestDistance = nil, math.huge
        for _, threat in ipairs(threats) do
            local rel = flat(threat.predicted - position)
            if rel.Magnitude > 0.05 then
                local forward = rel:Dot(front)
                local lateralOffset = math.abs(rel:Dot(lateral))
                if forward > 0 and forward <= 34 and lateralOffset <= 16 and threat.distance < nearestDistance then
                    nearest = threat; nearestDistance = threat.distance
                end
            end
        end
        if not nearest then return nil, nil, -math.huge end
        local rel = flat(nearest.predicted - position)
        local forwardGap = rel:Dot(front); local lateralOffset = rel:Dot(lateral)
        local frontBlocked = forwardGap > 0 and forwardGap < math.max(12, nearest.danger * 2.2) and math.abs(lateralOffset) < 13
        if not frontBlocked then return nil, nil, -math.huge end
        local candidates = {}
        for _, angle in ipairs(SETTINGS.sideGapAngles) do
            local rad = math.rad(angle); local c = math.cos(rad); local sn = math.sin(rad)
            candidates[#candidates + 1] = {dir = (front * c + lateral * sn).Unit, side = _OO1l1ll(561)}
            candidates[#candidates + 1] = {dir = (front * c - lateral * sn).Unit, side = _OO1l1ll(562)}
        end
        local best, bestScore, bestSide = nil, -math.huge, nil
        for _, item in ipairs(candidates) do
            local candidate = item.dir
            local clearance = routeClear(position, candidate, threats)
            local support = groundSupportScore(position, candidate, position.Y)
            local wallBlocked = invisWallHit(position, candidate, 16) ~= nil
            if not wallBlocked and support >= 3 and clearance >= -1 then
                local forwardProgress = candidate:Dot(front)
                local sideProgress = math.abs(candidate:Dot(lateral))
                local score = forwardProgress * SETTINGS.sideGapForwardBias
                    + sideProgress * 7 + math.min(clearance, 14) * 3.2 + support * 1.4
                local towardCatcher = rel:Dot(lateral)
                local away = item.side == _OO1l1ll(561) and -towardCatcher or towardCatcher
                score = score + math.clamp(away / 10, -1, 1) * 4
                if clearance >= SETTINGS.sideGapMinClearance then score = score + 5 end
                if score > bestScore then best = candidate; bestScore = score; bestSide = item.side end
            end
        end
        if best then return best, bestSide, bestScore end
        return nil, nil, -math.huge
    end
    local function chooseRunnerDirection(position, goal, threats)
        local desired = flat(goal - position); if desired.Magnitude < 0.05 then return Vector3.zero end
        desired = desired.Unit
        local sideGap, sideName = chooseSideGapDirection(position, desired, threats)
        if sideGap then
            runtime.sideGapDirection = sideGap
            runtime.sideGapUntil = os.clock() + SETTINGS.sideGapCommitTime
            runtime.sideGapReason = _OO1l1ll(563) .. tostring(sideName)
            return sideGap
        elseif runtime.sideGapDirection.Magnitude > 0.05 and os.clock() < runtime.sideGapUntil then
            local clear = routeClear(position, runtime.sideGapDirection, threats)
            if clear >= 0 and not invisWallHit(position, runtime.sideGapDirection, 14) then return runtime.sideGapDirection end
        else
            runtime.sideGapDirection = Vector3.zero; runtime.sideGapReason = _OO1l1ll(26)
        end
        if not SETTINGS.avoidCatchers or #threats == 0 then
            runtime.sideGapDirection = Vector3.zero; runtime.sideGapUntil = -math.huge; runtime.sideGapReason = _OO1l1ll(26)
            return desired
        end
        local candidates = {}
        addDirection(candidates, desired)
        for _, angle in ipairs({10, -10, 22, -22, 34, -34, 48, -48, 62, -62, 76, -76, 88, -88}) do addDirection(candidates, rotate(desired, angle)) end
        local blocker = threats[1]; local nearestScore = math.huge
        for _, threat in ipairs(threats) do
            local toThreat = flat(threat.position - position)
            local ahead = toThreat:Dot(desired); local distance = toThreat.Magnitude
            if ahead > 0 and distance < nearestScore then nearestScore = distance; blocker = threat end
        end
        if blocker then
            local toBlocker = flat(blocker.position - position)
            if toBlocker.Magnitude > 0.05 then
                local lateral = Vector3.new(-desired.Z, 0, desired.X)
                local side = toBlocker:Dot(lateral) >= 0 and -1 or 1
                addDirection(candidates, (desired + lateral * side * 0.55).Unit)
                addDirection(candidates, (desired + lateral * side * 0.95).Unit)
                addDirection(candidates, (desired - lateral * side * 0.55).Unit)
                addDirection(candidates, (desired - lateral * side * 0.95).Unit)
            end
        end
        if runtime.stuck then
            local lateral = Vector3.new(-desired.Z, 0, desired.X)
            addDirection(candidates, lateral); addDirection(candidates, -lateral)
            local center = getPlayfieldCenter()
            if center then addDirection(candidates, flat(center - position)) end
        end
        local best = desired; local bestScore = -math.huge
        local emergency = false
        for _, threat in ipairs(threats) do
            if threat.collisionRisk or threat.tackle or (threat.preTackle and threat.closing > 0) then emergency = true break end
        end
        for _, candidate in ipairs(candidates) do
            local progress = candidate:Dot(desired)
            local clearance = routeClear(position, candidate, threats)
            local wallBlocked = invisWallHit(position, candidate, 18) ~= nil
            if not wallBlocked then
                if emergency or progress >= 0.04 then
                    local score = progress * 10
                    score = score + math.min(clearance, 20) * 2.4 * SETTINGS.avoidStrength
                    if clearance < 0 then score = score - math.abs(clearance) * 18 * SETTINGS.avoidStrength
                    elseif clearance < 5 then score = score - (5 - clearance) * 5 * SETTINGS.avoidStrength end
                    if progress > 0.18 and math.abs(candidate:Dot(desired)) < 0.96 then
                        score = score + math.min(math.max(clearance, 0), 8) * 1.15
                    end
                    for _, threat in ipairs(threats) do
                        local away = flat(position - threat.intercept)
                        if away.Magnitude > 0.05 then
                            local urgency = math.clamp(
                                1 - math.min(threat.interceptGap, threat.timeToDanger * math.max(threat.closing, 1)) / math.max(threat.danger * 3, 1), 0, 1)
                            local weight = (threat.collisionRisk and 14 or 4.5) * SETTINGS.avoidStrength
                            if threat.tackle then weight = weight * 1.45 end
                            score = score + candidate:Dot(away.Unit) * urgency * weight
                        end
                    end
                    if runtime.edgeRisk then
                        local inward = runtime.edgeDirection
                        if inward.Magnitude > 0.05 then score = score + candidate:Dot(inward.Unit) * 7 end
                    end
                    if score > bestScore then bestScore = score; best = candidate end
                end
            end
        end
        if best.Magnitude < 0.05 then return desired end
        return best.Unit
    end
    local function chooseDashDirection(position, direction, threats)
        local desired = flat(direction); local root = getRoot()
        if desired.Magnitude < 0.05 and root then desired = flat(root.CFrame.LookVector) end
        if desired.Magnitude < 0.05 then return Vector3.zero end
        desired = desired.Unit
        local candidates = {}
        addDirection(candidates, desired)
        for _, angle in ipairs({18, -18, 32, -32, 48, -48, 64, -64, 82, -82, 90, -90}) do addDirection(candidates, rotate(desired, angle)) end
        if runtime.edgeRisk and runtime.edgeDirection.Magnitude > 0.05 then
            addDirection(candidates, runtime.edgeDirection)
            addDirection(candidates, rotate(runtime.edgeDirection, 28))
            addDirection(candidates, rotate(runtime.edgeDirection, -28))
        end
        local awaySum = Vector3.zero
        for i = 1, math.min(6, #threats) do
            local threat = threats[i]
            local away = flat(position - threat.predicted)
            if away.Magnitude > 0.05 then
                local weight = math.clamp(1 - threat.distance / 60, 0.2, 1)
                if threat.tackle then weight = weight * 2.2 elseif threat.preTackle then weight = weight * 1.5 end
                awaySum = awaySum + away.Unit * weight
            end
        end
        if awaySum.Magnitude > 0.05 then
            addDirection(candidates, awaySum.Unit)
            addDirection(candidates, rotate(awaySum.Unit, 28))
            addDirection(candidates, rotate(awaySum.Unit, -28))
        end
        local best = desired; local bestScore = -math.huge
        for _, candidate in ipairs(candidates) do
            local clearance = routeClear(position, candidate, threats)
            local progress = candidate:Dot(desired)
            local score = progress * 4.5 + math.min(clearance, 20) * 5.0
            if progress < -0.05 then score = score - 18 end
            if clearance < 0 then score = score - math.abs(clearance) * 22
            elseif clearance < 5 then score = score - (5 - clearance) * 5 end
            if awaySum.Magnitude > 0.05 then score = score + candidate:Dot(awaySum.Unit) * 7 end
            if runtime.edgeRisk and runtime.edgeDirection.Magnitude > 0.05 then score = score + candidate:Dot(runtime.edgeDirection.Unit) * 10 end
            for _, threat in ipairs(threats) do
                local dashPoint = position + candidate * math.min(getRunnerSpeed() * 0.45, 11)
                local gap = flat(dashPoint - threat.predicted).Magnitude
                if gap <= threat.danger * (threat.tackle and 1.55 or 1.2) then score = score - (threat.tackle and 14 or 8) end
            end
            if score > bestScore then bestScore = score; best = candidate end
        end
        return best.Unit
    end
