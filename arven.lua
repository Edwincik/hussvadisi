    local function chooseEdgeDirection(position, desired, goal, y)
        local dir = flat(desired); if dir.Magnitude < 0.05 then return Vector3.zero, false end
        dir = dir.Unit
        local now = os.clock()
        if runtime.edgeCheckPosition and runtime.edgeCheckDirection.Magnitude > 0.05
            and now - runtime.edgeCheckAt < 0.055
            and flat(position - runtime.edgeCheckPosition).Magnitude < 2.5
            and runtime.edgeCheckDirection:Dot(dir) > 0.96
            and runtime.edgeCheckGoal.Magnitude > 0.05
            and flat(goal - runtime.edgeCheckGoal).Magnitude < 8 then
            return runtime.edgeDirection, runtime.edgeRisk
        end
        local boundary = boundaryInwardDirection(position, y)
        local desiredRisk = edgeRiskForDirection(position, dir, y)
        local nearBoundary = boundary.Magnitude > 0.05 and boundary:Dot(dir) < 0.35
        runtime.edgeCheckAt = now; runtime.edgeCheckPosition = position
        runtime.edgeCheckDirection = dir; runtime.edgeCheckGoal = flat(goal)
        if not desiredRisk and not nearBoundary then
            runtime.edgeDirection = dir; runtime.edgeRisk = false; return dir, false
        end
        local toGoal = flat(goal - position)
        toGoal = toGoal.Magnitude < 0.05 and dir or toGoal.Unit
        local inward = boundary
        if inward.Magnitude < 0.05 then
            local center = getPlayfieldCenter()
            if center then inward = flat(center - position); if inward.Magnitude > 0.05 then inward = inward.Unit end end
        end
        local candidates = {}
        local function addCandidate(v)
            v = flat(v); if v.Magnitude < 0.05 then return end
            v = v.Unit
            for _, item in ipairs(candidates) do if item:Dot(v) > 0.985 then return end end
            candidates[#candidates + 1] = v
        end
        addCandidate(inward); addCandidate(toGoal); addCandidate(dir)
        local base = inward.Magnitude > 0.05 and inward or dir
        for _, angle in ipairs({-35, 35, -70, 70, 90, -90, 135, -135, 180}) do addCandidate(rotateEdge(base, angle)) end
        local best, bestScore = nil, -math.huge
        for _, candidate in ipairs(candidates) do
            local support = groundSupportScore(position, candidate, y)
            if support >= 6 then
                local score = support * 4.5 + candidate:Dot(toGoal) * 5
                if inward.Magnitude > 0.05 then score = score + candidate:Dot(inward) * (nearBoundary and 10 or 5) end
                if candidate:Dot(dir) > 0 then score = score + 2 end
                if score > bestScore then bestScore = score; best = candidate end
            end
        end
        if best then runtime.edgeDirection = best; runtime.edgeRisk = true; runtime.edgeRecoveryAt = now; return best, true end
        if inward.Magnitude > 0.05 then runtime.edgeDirection = inward; runtime.edgeRisk = true; return inward, true end
        runtime.edgeDirection = -dir; runtime.edgeRisk = true; return -dir, true
    end

