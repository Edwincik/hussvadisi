    local function updateThreats(now, position)
        if now - runtime.threatAt < 0.05 then return runtime.threats end
        runtime.threatAt = now; table.clear(runtime.threats)
        local runRoot = getRoot()
        local runVelocity = runRoot and flat(runRoot.AssemblyLinearVelocity) or Vector3.zero
        local runSpeed = math.max(getRunnerSpeed(), 1)
        if runVelocity.Magnitude < 3 and runtime.path.Magnitude > 0.05 then runVelocity = runtime.path.Unit * runSpeed end
